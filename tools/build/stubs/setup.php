/**
 * Unpack the archive into a target.
 *
 * Files are unpacked into a temporary folder first, so a damaged archive
 * leaves nothing behind. Then ticked names are moved into a backup folder,
 * existing .htaccess files get the application's rules added at the top, and
 * the application's files are moved into place.
 *
 * @param string   $archive Archive path.
 * @param array    $target  Target from setup_targets().
 * @param string[] $ticked  Archive paths the admin agreed to replace.
 * @return array|string ['backup' => folder or ""] on success, otherwise a message.
 */
function setup_unpack( $archive, $target, $ticked ) {
	@set_time_limit( 0 );

	$app     = $target['app'];
	$blocked = array_diff( array_keys( $target['conflicts'] ), $ticked );

	if ( ! empty( $blocked ) ) {
		return sprintf( 'These already exist in %s: %s. Tick them to replace them (they are backed up first), or move them away, then try again.', $app, implode( ', ', $blocked ) );
	}

	$staging = $app . '/.setup-' . bin2hex( random_bytes( 6 ) );
	$error   = setup_extract( $archive, $staging );

	if ( true !== $error ) {
		setup_remove( $staging );
		return $error;
	}

	// Ticked conflicts and placeholder pages go into a backup folder, keeping their paths.
	$aside  = array_values( array_intersect( array_merge( array_keys( $target['conflicts'] ), $target['placeholders'] ), $ticked ) );
	$backup = empty( $aside ) ? '' : $app . '/setup-backup-' . gmdate( 'Ymd-His' );

	foreach ( $aside as $path ) {
		$to = $backup . '/' . $path;

		if ( ( ! is_dir( dirname( $to ) ) && ! @mkdir( dirname( $to ), 0755, true ) ) || ! @rename( $app . '/' . $path, $to ) ) {
			setup_remove( $staging );
			return sprintf( 'Could not move %s into the backup folder %s. Check that %s is writable, then try again.', $path, $backup, $app );
		}
	}

	foreach ( $target['merges'] as $path ) {
		$error = setup_merge_htaccess( $staging . '/' . $path, $app . '/' . $path );

		if ( true !== $error ) {
			setup_remove( $staging );
			return $error;
		}
	}

	foreach ( $target['paths'] as $path ) {
		if ( in_array( $path, $target['merges'], true ) ) {
			continue;
		}

		if ( ! @rename( $staging . '/' . $path, $app . '/' . $path ) ) {
			setup_remove( $staging );
			return sprintf( 'Could not move %s into %s. Check that the folder is writable, delete what was already moved, then try again.', $path, $app );
		}
	}

	setup_remove( $staging );

	return array( 'backup' => $backup );
}

/**
 * Put the application's rules at the top of an existing .htaccess, keeping the rest.
 *
 * Hosts commonly keep their own lines in this file (for example cPanel's PHP
 * version handler); those must survive. The application's block comes first,
 * so its rewrite rules apply before any older ones.
 *
 * @param string $ours     The application's .htaccess (from the archive).
 * @param string $existing The .htaccess already in place.
 * @return true|string
 */
function setup_merge_htaccess( $ours, $existing ) {
	$current = @file_get_contents( $existing );
	$rules   = @file_get_contents( $ours );

	if ( false === $current || false === $rules ) {
		return sprintf( 'Could not read %s. Check its permissions, then try again.', $existing );
	}

	if ( false !== strpos( $current, '# BEGIN Smart License Server' ) ) {
		return true;
	}

	if ( false === @file_put_contents( $existing, rtrim( $rules ) . "\n\n" . $current ) ) {
		return sprintf( 'Could not update %s. Check that it is writable, then try again.', $existing );
	}

	return true;
}

/**
 * Copy the appended archive into its own file and list what it contains.
 *
 * The copy is checked against the archive's SHA-256, so a damaged upload is
 * reported before anything is unpacked. It is deleted when the request ends.
 *
 * @return array|string ['path' => archive, 'names' => paths] or a message.
 */
function setup_open_archive() {
	$path = @tempnam( sys_get_temp_dir(), 'smliser-setup-' );

	if ( false === $path ) {
		$path = __DIR__ . '/.setup-' . bin2hex( random_bytes( 6 ) ) . '.zip';
	}

	register_shutdown_function( 'setup_remove', $path );

	$error = setup_copy_payload( $path );

	if ( true !== $error ) {
		return $error;
	}

	$zip = new ZipArchive();

	if ( true !== $zip->open( $path ) ) {
		return 'The archive inside this file could not be opened. Upload this file again, then reload this page.';
	}

	$names  = array();
	$prefix = SETUP_ROOT . '/';

	for ( $i = 0; $i < $zip->numFiles; $i++ ) {
		$name = (string) $zip->getNameIndex( $i );

		if ( 0 === strpos( $name, $prefix ) && '' !== trim( substr( $name, strlen( $prefix ) ), '/' ) ) {
			$names[] = trim( substr( $name, strlen( $prefix ) ), '/' );
		}
	}

	$zip->close();

	return array(
		'path'  => $path,
		'names' => $names,
	);
}

/**
 * Copy the archive appended to this file into its own file, verifying its hash.
 *
 * @param string $archive Destination path.
 * @return true|string
 */
function setup_copy_payload( $archive ) {
	$in  = @fopen( __FILE__, 'rb' );
	$out = @fopen( $archive, 'wb' );

	if ( ! $in || ! $out ) {
		return 'Could not read this file or write a temporary copy of the archive. Check that this folder is writable.';
	}

	fseek( $in, __COMPILER_HALT_OFFSET__ );
	$hash = hash_init( 'sha256' );

	while ( ! feof( $in ) ) {
		$chunk = fread( $in, 1048576 );

		if ( false === $chunk ) {
			break;
		}

		hash_update( $hash, $chunk );

		if ( false === fwrite( $out, $chunk ) ) {
			fclose( $in );
			fclose( $out );
			return 'Could not write the temporary archive. The disk may be full.';
		}
	}

	fclose( $in );
	fclose( $out );

	if ( ! hash_equals( SETUP_SHA256, hash_final( $hash ) ) ) {
		return 'This file is incomplete or damaged, usually from an interrupted upload. Upload it again in binary mode (FTP clients sometimes change files in "ASCII" mode), then reload this page.';
	}

	return true;
}

/**
 * Extract the archive, file by file, without its top-level folder.
 *
 * @param string $archive Archive path.
 * @param string $staging Folder to extract into.
 * @return true|string
 */
function setup_extract( $archive, $staging ) {
	$zip = new ZipArchive();

	if ( true !== $zip->open( $archive ) ) {
		return 'The archive inside this file could not be opened. Upload this file again, then reload this page.';
	}

	if ( ! @mkdir( $staging, 0755 ) ) {
		$zip->close();
		return sprintf( 'Could not create a temporary folder in %s. Check that it is writable.', dirname( $staging ) );
	}

	$prefix = SETUP_ROOT . '/';

	for ( $i = 0; $i < $zip->numFiles; $i++ ) {
		$name = (string) $zip->getNameIndex( $i );

		if ( 0 !== strpos( $name, $prefix ) ) {
			continue;
		}

		$relative = substr( $name, strlen( $prefix ) );

		if ( '' === $relative || '' === trim( $relative, '/' ) ) {
			continue;
		}

		// Never write outside the staging folder.
		if ( false !== strpos( $relative, '\\' ) || false !== strpos( $relative, ':' ) || in_array( '..', explode( '/', $relative ), true ) ) {
			$zip->close();
			return 'The archive contains an unsafe path and was not unpacked.';
		}

		$path = $staging . '/' . rtrim( $relative, '/' );

		if ( '/' === substr( $relative, -1 ) ) {
			if ( ! is_dir( $path ) && ! @mkdir( $path, 0755, true ) ) {
				$zip->close();
				return 'Could not create the folder ' . $relative . '.';
			}
			continue;
		}

		if ( ! is_dir( dirname( $path ) ) && ! @mkdir( dirname( $path ), 0755, true ) ) {
			$zip->close();
			return 'Could not create the folder for ' . $relative . '.';
		}

		$stream = $zip->getStream( $name );
		$target = @fopen( $path, 'wb' );

		if ( ! $stream || ! $target ) {
			$zip->close();
			return 'Could not write ' . $relative . '. The disk may be full.';
		}

		stream_copy_to_stream( $stream, $target );
		fclose( $stream );
		fclose( $target );

		// Unix permissions stored in the archive (e.g. the executable CLI entry).
		$opsys = 0;
		$attr  = 0;

		if ( $zip->getExternalAttributesIndex( $i, $opsys, $attr ) && ZipArchive::OPSYS_UNIX === $opsys && ( $attr >> 16 ) & 0777 ) {
			@chmod( $path, ( $attr >> 16 ) & 0777 );
		}
	}

	$zip->close();

	return true;
}

/**
 * Remove a file or folder tree.
 *
 * @param string $path Path.
 * @return void
 */
function setup_remove( $path ) {
	if ( is_link( $path ) || is_file( $path ) ) {
		@unlink( $path );
		return;
	}

	if ( ! is_dir( $path ) ) {
		return;
	}

	foreach ( array_diff( (array) scandir( $path ), array( '.', '..' ) ) as $entry ) {
		setup_remove( $path . '/' . $entry );
	}

	@rmdir( $path );
}

