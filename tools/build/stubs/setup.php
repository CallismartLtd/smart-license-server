/**
 * Escape text for HTML.
 *
 * @param string $text Text.
 * @return string
 */
function setup_e( $text ) {
	return htmlspecialchars( (string) $text, ENT_QUOTES, 'UTF-8' );
}

/**
 * The first page: where the files can go and what is in the way, or what prevents unpacking.
 *
 * @param array    $targets  Targets from setup_targets().
 * @param string[] $problems Problems found.
 * @param string   $selected Target submitted last, if any.
 * @return string
 */
function setup_start_html( $targets, $problems, $selected ) {
	$html = '';

	if ( ! empty( $problems ) ) {
		$items = '';

		foreach ( $problems as $problem ) {
			$items .= '<li>' . setup_e( $problem ) . '</li>';
		}

		$html .= '<p>The files cannot be unpacked yet:</p><ul class="problems">' . $items . '</ul>';
	}

	$usable = [];

	foreach ( $targets as $key => $target ) {
		if ( empty( $target['problems'] ) ) {
			$usable[ $key ] = $target;
		}
	}

	if ( empty( $usable ) ) {
		foreach ( $targets as $target ) {
			$html .= '<p>' . setup_e( $target['label'] ) . ' (<code>' . setup_e( $target['app'] ) . '</code>) cannot be used:</p><ul class="problems">';

			foreach ( $target['problems'] as $problem ) {
				$html .= '<li>' . setup_e( $problem ) . '</li>';
			}

			$html .= '</ul>';
		}

		return $html;
	}

	// The choice shown as selected: the last one submitted, else the recommended one, else the first usable.
	if ( ! isset( $usable[ $selected ] ) ) {
		$selected = isset( $usable['parent'] ) && $usable['parent']['recommended'] ? 'parent' : ( isset( $usable['here'] ) ? 'here' : key( $usable ) );
	}

	$html .= '<form method="post">';

	if ( count( $targets ) > 1 ) {
		$html .= '<p>This file is in a folder called <code>public</code>, which is often the folder a domain points at. Choose where ' . setup_e( SETUP_TITLE ) . ' should go.</p>'
			. '<fieldset><legend>Where should the application go?</legend>';

		foreach ( $targets as $key => $target ) {
			$disabled = ! isset( $usable[ $key ] );
			$html .= '<label class="choice' . ( $disabled ? ' disabled' : '' ) . '"><input type="radio" name="target" value="' . setup_e( $key ) . '"'
				. ( $key === $selected ? ' checked' : '' ) . ( $disabled ? ' disabled' : '' ) . '> '
				. '<span><strong>' . setup_e( $target['label'] ) . '</strong>' . ( $target['recommended'] ? ' <span class="badge">Recommended</span>' : '' )
				. '<br><code>' . setup_e( $target['app'] ) . '</code>'
				. '<span class="hint">' . setup_e( $target['description'] ) . '</span>';

			foreach ( $target['problems'] as $problem ) {
				$html .= '<span class="warning">' . setup_e( $problem ) . '</span>';
			}

			$html .= '</span></label>';
		}

		$html .= '</fieldset>';
	} else {
		$html .= '<p>This unpacks ' . setup_e( SETUP_TITLE . ' ' . SETUP_VERSION ) . ' into this folder:</p>'
			. '<p><code>' . setup_e( $selected ? $usable[ $selected ]['app'] : '' ) . '</code></p>'
			. '<input type="hidden" name="target" value="' . setup_e( $selected ) . '">';
	}

	foreach ( $usable as $key => $target ) {
		$html .= '<div class="plan" data-plan="' . setup_e( $key ) . '">' . setup_plan_html( $target, count( $usable ) > 1 ) . '</div>';
	}

	$html .= '<p>It takes a few seconds. Afterwards this file deletes itself, and you continue with the setup in your browser.</p>'
		. '<button type="submit">Unpack the files</button></form>';

	// Show only the details of the chosen place. Without JavaScript, all are shown with their headings.
	if ( count( $usable ) > 1 ) {
		$html .= '<script>(function(){var r=document.querySelectorAll(\'input[name="target"]\'),p=document.querySelectorAll(\'[data-plan]\');'
			. 'function u(){var c=document.querySelector(\'input[name="target"]:checked\'),v=c?c.value:"";for(var i=0;i<p.length;i++){p[i].hidden=p[i].getAttribute("data-plan")!==v;}}'
			. 'for(var i=0;i<r.length;i++){r[i].addEventListener("change",u);}u();})();</script>';
	}

	return $html;
}

/**
 * What unpacking into one target will change: names in the way, .htaccess merges, placeholder pages.
 *
 * @param array $target    Target from setup_targets().
 * @param bool  $named     Whether to name the target in the headings (more than one choice).
 * @return string
 */
function setup_plan_html( $target, $named ) {
	$key    = $target['key'];
	$app    = $target['app'];
	$suffix = $named ? ' (' . $target['label'] . ')' : '';
	$html   = '';

	if ( ! empty( $target['conflicts'] ) ) {
		$html .= '<h2>Already in the way' . setup_e( $suffix ) . '</h2>'
			. '<p>The application needs these names in <code>' . setup_e( $app ) . '</code>, and they already exist. '
			. 'Tick each one to replace it: the existing one is first moved to a <code>setup-backup-&lt;date&gt;</code> folder there, so nothing is lost. '
			. 'Unpacking stops while any of them is unticked.</p>';

		foreach ( $target['conflicts'] as $path => $type ) {
			$html .= '<label class="check"><input type="checkbox" name="replace[]" value="' . setup_e( $key . ':' . $path ) . '"> '
				. '<span>Replace <code>' . setup_e( $path ) . '</code>'
				. '<span class="hint">An existing ' . setup_e( $type ) . '. It is moved to <code>setup-backup-&lt;date&gt;/' . setup_e( $path ) . '</code>, and the application&rsquo;s own ' . setup_e( $path ) . ' takes its place.</span></span></label>';
		}
	}

	if ( ! empty( $target['placeholders'] ) ) {
		$html .= '<h2>Placeholder pages' . setup_e( $suffix ) . '</h2>';

		foreach ( $target['placeholders'] as $path ) {
			$html .= '<label class="check"><input type="checkbox" name="replace[]" value="' . setup_e( $key . ':' . $path ) . '" checked> '
				. '<span>Move <code>' . setup_e( $path ) . '</code> aside'
				. '<span class="hint">Web servers usually show this page before index.php, so it would hide the application. It is moved to <code>setup-backup-&lt;date&gt;/' . setup_e( $path ) . '</code>. Untick to keep it where it is.</span></span></label>';
		}
	}

	if ( ! empty( $target['merges'] ) ) {
		$html .= '<h2>Existing .htaccess files' . setup_e( $suffix ) . '</h2><ul class="notes">';

		foreach ( $target['merges'] as $path ) {
			$html .= '<li><code>' . setup_e( $path ) . '</code> stays: the application&rsquo;s rules are added at its top, and the lines already in it are kept.</li>';
		}

		$html .= '</ul>';
	}

	if ( '' === $html ) {
		$html = '<p class="hint">Nothing in <code>' . setup_e( $app ) . '</code> is in the way.</p>';
	}

	return $html;
}

/**
 * The final page: where to go next.
 *
 * @param array  $target       Target the files were unpacked into.
 * @param string $backup       Backup folder, or "" when nothing was moved aside.
 * @param bool   $self_deleted Whether this file was deleted.
 * @return string
 */
function setup_done_html( $target, $backup, $self_deleted ) {
	$app    = $target['app'];
	$public = $app . '/public';
	$html   = '<p>' . setup_e( SETUP_TITLE . ' ' . SETUP_VERSION ) . ' was unpacked into <code>' . setup_e( $app ) . '</code>.</p>';

	if ( '' !== $backup ) {
		$html .= '<p>What it replaced is kept in <code>' . setup_e( $backup ) . '</code>. Delete that folder once you no longer need it.</p>';
	}

	if ( setup_document_root() === setup_real( $public ) ) {
		// The document root is the public folder: the layout every server needs.
		$html .= '<h2>Next: run the installer</h2>'
			. '<p><a href="./?install">Open the installer</a> and follow the steps.</p>';
	} elseif ( setup_reads_htaccess() ) {
		// The .htaccess shipped in the application folder sends every request into public/,
		// so the site works and nothing else in the folder is reachable.
		$html .= '<h2>Next: run the installer</h2>'
			. '<p><a href="./?install">Open the installer</a> and follow the steps.</p>'
			. '<p class="hint">Recommended when you can: set your domain&rsquo;s document root to <code>' . setup_e( $public ) . '</code>. '
			. 'Until then, the <code>.htaccess</code> file in <code>' . setup_e( $app ) . '</code> keeps everything outside <code>public</code> out of reach; do not delete it.</p>';
	} else {
		$html .= '<h2>Before you continue: change the document root</h2>'
			. '<p class="warning">This web server does not read <code>.htaccess</code> files, so everything in the application folder can be downloaded from the web, including the settings file the installer creates. Do not run the installer yet.</p>'
			. '<p>Set your domain&rsquo;s document root to:</p>'
			. '<p><code>' . setup_e( $public ) . '</code></p>'
			. '<p>Then open <code>https://your-domain/install</code>. Ready-made configurations for nginx and Caddy are in the <code>server</code> folder.</p>';
	}

	if ( ! $self_deleted ) {
		$html .= '<p class="warning">This file could not delete itself. Delete <code>' . setup_e( __FILE__ ) . '</code> now.</p>';
	}

	return $html;
}

/**
 * Whether the web server applies .htaccess files (Apache, LiteSpeed).
 *
 * Unknown servers count as not reading them, so the page never claims a
 * protection that may not exist.
 *
 * @return bool
 */
function setup_reads_htaccess() {
	$software = strtolower( isset( $_SERVER['SERVER_SOFTWARE'] ) ? (string) $_SERVER['SERVER_SOFTWARE'] : '' );

	return false !== strpos( $software, 'apache' ) || false !== strpos( $software, 'litespeed' );
}

