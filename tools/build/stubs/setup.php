/**
 * The places the application can be unpacked into, keyed "here" and "parent".
 *
 * Each target describes what unpacking there would do: the application
 * folder, the archive paths that would be moved in, the names already in the
 * way, the .htaccess files that would be merged, placeholder pages that would
 * hide the application, and anything that rules the target out.
 *
 * @param string   $dir   Folder this file is in.
 * @param string[] $names Paths inside the archive (without its top-level folder).
 * @return array<string, array>
 */
function setup_targets( $dir, $names ) {
	$top    = [];
	$public = [];

	foreach ( $names as $name ) {
		$parts            = explode( '/', $name );
		$top[ $parts[0] ] = true;

		if ( 'public' === $parts[0] && isset( $parts[1] ) ) {
			$public[ $parts[1] ] = true;
		}
	}

	$docroot = setup_document_root();
	$targets = [];
	$parent  = dirname( $dir );

	// Only a folder called "public" can become the application's public folder.
	if ( 'public' === basename( $dir ) && $parent !== $dir ) {
		$paths = [];

		foreach ( array_keys( $top ) as $entry ) {
			if ( 'public' !== $entry ) {
				$paths[] = $entry;
			}
		}

		foreach ( array_keys( $public ) as $entry ) {
			$paths[] = 'public/' . $entry;
		}

		$targets['parent'] = setup_target(
			'parent',
			$parent,
			$paths,
			'One level up',
			'The application goes into the parent folder and this folder becomes its public folder: the website is still served from here, while settings, code and data sit outside it, where they cannot be downloaded. Choose this when your domain points at this folder.'
		);

		$targets['parent']['recommended'] = ( '' === $docroot || $docroot === setup_real( $dir ) );
	}

	$targets['here'] = setup_target(
		'here',
		$dir,
		array_keys( $top ),
		isset( $targets['parent'] ) ? 'Into this folder' : 'This folder',
		isset( $targets['parent'] )
			? 'The application goes here, with its own public folder inside this one. Choose this when this folder is meant to hold the application, for example a folder inside a site that happens to be called "public".'
			: 'The application goes into this folder, with its own public folder inside.'
	);

	return $targets;
}

/**
 * Describe unpacking into one folder.
 *
 * @param string   $key         "here" or "parent".
 * @param string   $app         Application folder.
 * @param string[] $paths       Archive paths moved into the application folder as they are.
 * @param string   $label       Short name of the choice.
 * @param string   $description What choosing it means.
 * @return array
 */
function setup_target( $key, $app, $paths, $label, $description ) {
	$target = [
		'key'          => $key,
		'app'          => $app,
		'label'        => $label,
		'description'  => $description,
		'recommended'  => false,
		'paths'        => $paths,
		'conflicts'    => [],   // Archive path => "file" | "folder" | "link".
		'merges'       => [],   // Existing .htaccess files the application's rules are added to.
		'placeholders' => [],   // Pages that would be shown instead of the application.
		'problems'     => [],
	];

	foreach ( $paths as $path ) {
		$dest = $app . '/' . $path;

		if ( '.htaccess' === basename( $path ) && is_file( $dest ) && ! is_link( $dest ) ) {
			$target['merges'][] = $path;
		} elseif ( is_link( $dest ) || file_exists( $dest ) ) {
			$target['conflicts'][ $path ] = is_link( $dest ) ? 'link' : ( is_dir( $dest ) ? 'folder' : 'file' );
		}
	}

	ksort( $target['conflicts'] );

	// An existing public folder keeps whatever the host put there. Web servers
	// usually prefer index.html over index.php, so a placeholder page would
	// hide the application.
	if ( is_dir( $app . '/public' ) && ! isset( $target['conflicts']['public'] ) ) {
		foreach ( [ 'index.html', 'index.htm', 'default.html', 'default.htm' ] as $page ) {
			if ( is_file( $app . '/public/' . $page ) && ! in_array( 'public/' . $page, $paths, true ) ) {
				$target['placeholders'][] = 'public/' . $page;
			}
		}
	}

	$existing = [];

	foreach ( [ 'bootstrap.php', 'system', 'manifest.json' ] as $name ) {
		if ( file_exists( $app . '/' . $name ) ) {
			$existing[] = $name;
		}
	}

	if ( ! empty( $existing ) ) {
		$target['problems'][] = sprintf( '%s already contains an installation (%s). This file only installs where there is none.', $app, implode( ', ', $existing ) );
	}

	$folders = [ $app ];

	if ( 'parent' === $key ) {
		$folders[] = $app . '/public';
	}

	foreach ( $folders as $folder ) {
		if ( ! is_writable( $folder ) ) {
			$target['problems'][] = sprintf( 'The web server cannot write to %s. Allow writing to it (for example, permissions 755 owned by the account PHP runs as), then reload this page.', $folder );
		}
	}

	return $target;
}

/**
 * The ticked checkboxes that belong to a target, as archive paths.
 *
 * Each checkbox value is "<target>:<path>", so the lists of both targets can
 * sit in the same form.
 *
 * @param string   $key    Chosen target.
 * @param string[] $ticked Submitted checkbox values.
 * @return string[]
 */
function setup_ticked( $key, $ticked ) {
	$paths  = [];
	$prefix = $key . ':';

	foreach ( $ticked as $value ) {
		if ( is_string( $value ) && 0 === strpos( $value, $prefix ) ) {
			$paths[] = substr( $value, strlen( $prefix ) );
		}
	}

	return $paths;
}

/**
 * The web server's document root, resolved, or "" when unknown (always so in the console).
 *
 * @return string
 */
function setup_document_root() {
	return isset( $_SERVER['DOCUMENT_ROOT'] ) && '' !== $_SERVER['DOCUMENT_ROOT'] ? setup_real( (string) $_SERVER['DOCUMENT_ROOT'] ) : '';
}

/**
 * Resolve a path, keeping it as given when it does not exist.
 *
 * @param string $path Path.
 * @return string
 */
function setup_real( $path ) {
	$real = realpath( $path );

	return false === $real ? rtrim( $path, '/\\' ) : $real;
}

