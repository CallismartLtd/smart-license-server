/**
 * Whether questions can be asked: standard input is a terminal.
 *
 * @return bool
 */
function setup_cli_interactive() {
	if ( ! defined( 'STDIN' ) ) {
		return false;
	}

	if ( function_exists( 'stream_isatty' ) ) {
		return stream_isatty( STDIN );
	}

	return function_exists( 'posix_isatty' ) && posix_isatty( STDIN );
}

/**
 * Ask a yes/no question.
 *
 * @param string $question Question.
 * @param bool   $default  Answer used when only Enter is pressed (or input ends).
 * @return bool
 */
function setup_cli_ask( $question, $default ) {
	echo $question . ( $default ? ' [Y/n] ' : ' [y/N] ' );

	$line = fgets( STDIN );

	if ( false === $line || '' === trim( $line ) ) {
		return $default;
	}

	return in_array( strtolower( trim( $line ) ), [ 'y', 'yes' ], true );
}

/**
 * Ask which of several targets to use.
 *
 * @param array<string, array> $usable Usable targets.
 * @return string Key of the chosen target.
 */
function setup_cli_choose( $usable ) {
	$keys    = array_keys( $usable );
	$default = 1;

	echo "Where should the application go?\n";

	foreach ( $keys as $index => $key ) {
		$target = $usable[ $key ];

		if ( $target['recommended'] ) {
			$default = $index + 1;
		}

		echo sprintf( "  %d) %s%s\n     %s\n     %s\n", $index + 1, $target['label'], $target['recommended'] ? ' (recommended)' : '', $target['app'], $target['description'] );
	}

	while ( true ) {
		echo sprintf( 'Choose 1-%d [%d]: ', count( $keys ), $default );

		$line = fgets( STDIN );

		if ( false === $line ) {
			return $keys[ $default - 1 ];
		}

		$line = trim( $line );

		if ( '' === $line ) {
			return $keys[ $default - 1 ];
		}

		if ( ctype_digit( $line ) && (int) $line >= 1 && (int) $line <= count( $keys ) ) {
			return $keys[ (int) $line - 1 ];
		}
	}
}

/**
 * Print one or more error messages to standard error.
 *
 * @param string|string[] $messages Message(s).
 * @return int Exit code 1, so callers can `return setup_cli_fail( ... )`.
 */
function setup_cli_fail( $messages ) {
	$err = @fopen( 'php://stderr', 'w' );

	foreach ( (array) $messages as $message ) {
		if ( $err ) {
			fwrite( $err, 'Error: ' . $message . "\n" );
		}
	}

	if ( $err ) {
		fclose( $err );
	}

	return 1;
}

/**
 * What unpacking will do, as plain text.
 *
 * @param array    $target Target from setup_targets().
 * @param string[] $ticked Archive paths that will be moved aside.
 * @return string
 */
function setup_plan_text( $target, $ticked ) {
	$text = "\nPlan\n"
		. '  Application folder: ' . $target['app'] . "\n";

	if ( 'parent' === $target['key'] ) {
		$text .= '  Public folder:      ' . $target['app'] . "/public (this folder)\n";
	}

	$any = false;

	foreach ( $target['conflicts'] as $path => $type ) {
		$any   = true;
		$text .= sprintf( "  - replace existing %s \"%s\" (moved to setup-backup-<date>/%s)\n", $type, $path, $path );
	}

	foreach ( $target['placeholders'] as $path ) {
		$any = true;

		if ( in_array( $path, $ticked, true ) ) {
			$text .= sprintf( "  - move placeholder page \"%s\" aside (setup-backup-<date>/%s)\n", $path, $path );
		} else {
			$text .= sprintf( "  - keep placeholder page \"%s\" (it may hide the application)\n", $path );
		}
	}

	foreach ( $target['merges'] as $path ) {
		$any   = true;
		$text .= sprintf( "  - add the application's rules to the top of existing \"%s\", keeping its lines\n", $path );
	}

	if ( ! $any ) {
		$text .= "  Nothing in the application folder is in the way.\n";
	}

	return $text . "\n";
}

