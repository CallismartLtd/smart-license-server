/**
 * Run the installer from the console.
 *
 * Interactive when a terminal is attached: it asks where to unpack, what to
 * replace, and for confirmation. Without a terminal (scripts, CI, SSH
 * commands) nothing is guessed: every decision must be given as an option,
 * and anything missing is reported instead of assumed.
 *
 * @param string[] $argv Raw arguments, the script name first.
 * @return int Exit code: 0 on success, 1 on failure.
 */
function setup_cli( $argv ) {
	@ini_set( 'display_errors', 'stderr' );

	$options = setup_cli_options( array_slice( $argv, 1 ) );

	if ( is_string( $options ) ) {
		return setup_cli_fail( $options );
	}

	if ( $options['help'] ) {
		echo setup_cli_usage( isset( $argv[0] ) ? basename( (string) $argv[0] ) : basename( __FILE__ ) );
		return 0;
	}

	$problems = setup_problems();

	if ( ! empty( $problems ) ) {
		return setup_cli_fail( $problems );
	}

	$archive = setup_open_archive();

	if ( is_string( $archive ) ) {
		return setup_cli_fail( $archive );
	}

	$targets     = setup_targets( __DIR__, $archive['names'] );
	$interactive = setup_cli_interactive();
	$usable      = [];

	foreach ( $targets as $key => $target ) {
		if ( empty( $target['problems'] ) ) {
			$usable[ $key ] = $target;
		}
	}

	if ( empty( $usable ) ) {
		$messages = [];

		foreach ( $targets as $target ) {
			foreach ( $target['problems'] as $problem ) {
				$messages[] = $target['label'] . ' (' . $target['app'] . '): ' . $problem;
			}
		}

		return setup_cli_fail( $messages );
	}

	// Where to unpack.
	if ( '' !== $options['target'] ) {
		if ( ! isset( $targets[ $options['target'] ] ) ) {
			return setup_cli_fail( sprintf( '--target=%s is not available here. Available: %s.', $options['target'], implode( ', ', array_keys( $targets ) ) ) );
		}

		if ( ! isset( $usable[ $options['target'] ] ) ) {
			return setup_cli_fail( $targets[ $options['target'] ]['problems'] );
		}

		$key = $options['target'];
	} elseif ( 1 === count( $usable ) ) {
		$key = key( $usable );
	} elseif ( $interactive ) {
		$key = setup_cli_choose( $usable );
	} else {
		return setup_cli_fail( sprintf( 'This file can unpack to more than one place. Choose with --target=%s.', implode( ' or --target=', array_keys( $usable ) ) ) );
	}

	$target = $usable[ $key ];

	// What to replace.
	$ticked = [];

	if ( $options['replace-all'] ) {
		$ticked = array_keys( $target['conflicts'] );
	} else {
		$unknown = array_diff( $options['replace'], array_keys( $target['conflicts'] ) );

		if ( ! empty( $unknown ) ) {
			return setup_cli_fail( sprintf( 'Not in the way in %s, so nothing to replace: %s.', $target['app'], implode( ', ', $unknown ) ) );
		}

		$ticked = $options['replace'];
	}

	$open = array_diff( array_keys( $target['conflicts'] ), $ticked );

	foreach ( $open as $path ) {
		if ( $interactive && setup_cli_ask( sprintf( 'Replace existing %s "%s" in %s? It is moved to a backup folder first.', $target['conflicts'][ $path ], $path, $target['app'] ), false ) ) {
			$ticked[] = $path;
		}
	}

	$open = array_diff( array_keys( $target['conflicts'] ), $ticked );

	if ( ! empty( $open ) ) {
		return setup_cli_fail( sprintf( 'These already exist in %s: %s. Replace them with --replace=<names> (or --replace-all; they are backed up first), or move them away.', $target['app'], implode( ', ', $open ) ) );
	}

	// Placeholder pages hide the application, so they are moved aside unless told otherwise.
	if ( ! $options['keep-placeholders'] ) {
		$ticked = array_merge( $ticked, $target['placeholders'] );
	}

	echo setup_plan_text( $target, $ticked );

	if ( ! $options['yes'] ) {
		if ( ! $interactive ) {
			return setup_cli_fail( 'No terminal to confirm on. Review the plan above and run again with --yes.' );
		}

		if ( ! setup_cli_ask( 'Unpack the files now?', true ) ) {
			echo "Nothing was changed.\n";
			return 1;
		}
	}

	$result = setup_unpack( $archive['path'], $target, $ticked );

	if ( ! is_array( $result ) ) {
		return setup_cli_fail( $result );
	}

	$self_deleted = @unlink( __FILE__ );

	echo "\n" . setup_done_text( $target, $result['backup'], $self_deleted );

	return 0;
}

/**
 * Parse console arguments.
 *
 * @param string[] $args Arguments after the script name.
 * @return array|string Options, or a message when an argument is not understood.
 */
function setup_cli_options( $args ) {
	$options = [
		'help'              => false,
		'target'            => '',
		'replace'           => [],
		'replace-all'       => false,
		'keep-placeholders' => false,
		'yes'               => false,
	];

	foreach ( $args as $arg ) {
		if ( '-h' === $arg ) {
			$arg = '--help';
		} elseif ( '-y' === $arg ) {
			$arg = '--yes';
		}

		if ( 0 !== strpos( $arg, '--' ) ) {
			return sprintf( 'Unexpected argument "%s". Run with --help to see the options.', $arg );
		}

		$parts = explode( '=', substr( $arg, 2 ), 2 );
		$name  = $parts[0];
		$value = isset( $parts[1] ) ? $parts[1] : null;

		switch ( $name ) {
			case 'help':
			case 'yes':
			case 'replace-all':
			case 'keep-placeholders':
				if ( null !== $value ) {
					return sprintf( '--%s does not take a value.', $name );
				}

				$options[ $name ] = true;
				break;

			case 'target':
				if ( 'here' !== $value && 'parent' !== $value ) {
					return '--target must be "here" or "parent".';
				}

				$options['target'] = $value;
				break;

			case 'replace':
				if ( null === $value || '' === trim( $value ) ) {
					return '--replace needs a comma-separated list of names, for example --replace=public,storage.';
				}

				foreach ( explode( ',', $value ) as $path ) {
					$path = trim( $path, " \t/" );

					if ( '' !== $path ) {
						$options['replace'][] = $path;
					}
				}
				break;

			default:
				return sprintf( 'Unknown option --%s. Run with --help to see the options.', $name );
		}
	}

	return $options;
}

