/**
 * Server requirements that prevent unpacking anywhere, as plain-language messages.
 *
 * @return string[]
 */
function setup_problems() {
	$problems = array();

	if ( '' !== SETUP_PHP && version_compare( PHP_VERSION, SETUP_PHP, '<' ) ) {
		$problems[] = sprintf( '%s needs PHP %s or newer; this server runs PHP %s. Choose a newer PHP version in your hosting control panel, then reload this page.', SETUP_TITLE, SETUP_PHP, PHP_VERSION );
	}

	$missing = array();

	foreach ( array_unique( array_merge( array( 'zip' ), (array) SETUP_EXTENSIONS ) ) as $extension ) {
		if ( ! extension_loaded( $extension ) ) {
			$missing[] = $extension;
		}
	}

	if ( ! empty( $missing ) ) {
		$problems[] = sprintf( 'These PHP extensions are missing: %s. Enable them in your hosting control panel (often under "PHP extensions" or "Select PHP version"), then reload this page.', implode( ', ', $missing ) );
	}

	return $problems;
}

