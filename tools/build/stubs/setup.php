<?php
/**
 * Single-file installer: upload this one file, open it in a browser, and it
 * unpacks the application, then hands over to the web installer.
 *
 * The application normally goes into the folder this file is in. When that
 * folder is called "public" (hosts and control panels often create the
 * document root under that name), the parent folder is offered too: the
 * application then goes one level up and its public files join this folder,
 * so the web server keeps serving this folder and everything else stays out
 * of reach.
 *
 * Names the application needs that already exist are listed with a checkbox.
 * Ticked ones are moved into a backup folder before the application's own
 * files take their place; nothing is deleted.
 *
 * The application archive is appended after __halt_compiler() below. This file
 * is generated by tools/build; do not edit it by hand.
 *
 * Kept compatible with old PHP versions on purpose, so a server that is too
 * old shows a clear message instead of a syntax error.
 */

const SETUP_TITLE      = '{{TITLE}}';
const SETUP_VERSION    = '{{VERSION}}';
const SETUP_ROOT       = '{{ROOT}}';      // Top-level folder inside the archive; stripped when unpacking.
const SETUP_SHA256     = '{{SHA256}}';    // SHA-256 of the appended archive.
const SETUP_PHP        = '{{PHP}}';       // Minimum PHP version ("" when none).
const SETUP_EXTENSIONS = '{{EXTENSIONS}}';

@ini_set( 'display_errors', '0' );
header( 'Content-Type: text/html; charset=utf-8' );
header( 'Cache-Control: no-store' );
header( 'X-Robots-Tag: noindex' );

$problems = setup_problems();
$archive  = null;
$targets  = array();
$selected = '';

if ( empty( $problems ) ) {
	$archive = setup_open_archive();

	if ( is_string( $archive ) ) {
		$problems[] = $archive;
		$archive    = null;
	} else {
		$targets = setup_targets( __DIR__, $archive['names'] );
	}
}

if ( null !== $archive && 'POST' === ( isset( $_SERVER['REQUEST_METHOD'] ) ? $_SERVER['REQUEST_METHOD'] : 'GET' ) ) {
	$selected = isset( $_POST['target'] ) ? (string) $_POST['target'] : '';
	$ticked   = isset( $_POST['replace'] ) ? (array) $_POST['replace'] : array();

	if ( ! isset( $targets[ $selected ] ) || ! empty( $targets[ $selected ]['problems'] ) ) {
		$problems[] = 'Choose where to unpack the files.';
	} else {
		$result = setup_unpack( $archive['path'], $targets[ $selected ], setup_ticked( $selected, $ticked ) );

		if ( is_array( $result ) ) {
			$self_deleted = @unlink( __FILE__ );
			setup_page( 'Files are in place', setup_done_html( $targets[ $selected ], $result['backup'], $self_deleted ) );
			exit;
		}

		$problems[] = $result;
	}
}

setup_page( 'Install ' . SETUP_TITLE, setup_start_html( $targets, $problems, $selected ) );
exit;

