	public function __construct(
		protected MonetizationRegistry $registry,
		protected URLManager $urlmanager,
		Guard $guard
	) {
		$this->guard = $guard;
	}
	/**
	 * Creates or updates a pricing tier of an app, creating the app's
	 * monetization when it has none.
	 *
	 * Request fields: app_type, app_id, tier_id (to update a tier),
	 * tier_name, term_unit (see PricingTier::get_term_units()), term_length,
	 * max_sites (empty for unlimited), features (comma or line separated),
	 * provider_id (a provider ID, without channel; empty for none) and
	 * provider_data[<provider ID>][<field>] (the provider's tier fields,
	 * see MonetizationProviderInterface::get_tier_schema()).
	 * 
	 * @param Request $request The portable request object generated by the adapter.
	 * @return Response The portable response object containing data or an exception.
	 */
	public function save_monetization( Request $request ) : Response {
		try {
			$app_id      = (int) $request->get( 'app_id', 0 );
			$tier_id     = (int) $request->get( 'tier_id', 0 );
			$max_sites   = trim( (string) $request->get( 'max_sites', '' ) );
			$provider_id = trim( (string) $request->get( 'provider_id', '' ) );
			$features    = preg_split( '/[,\r\n]+/', (string) $request->get( 'features', '' ) ) ?: [];

			$app_type = $request->get( 'app_type' )
				?: throw new RequestException( 'missing_app_type', 'Item type is required', [ 'field_id' => 'app_type', 'status' => 400 ] );

			$tier_name = $request->get( 'tier_name' )
				?: throw new RequestException( 'missing_tier_name', 'Tier name is required', [ 'field_id' => 'tier_name', 'status' => 400 ] );

			$term_unit = $request->get( 'term_unit' )
				?: throw new RequestException( 'missing_term_unit', 'Choose the license term', [ 'field_id' => 'term_unit', 'status' => 400 ] );

			$provider = '' === $provider_id ? null : $this->registry->get_provider( $provider_id );

			if ( '' !== $provider_id && ( ! $provider || $provider::get_id() !== $provider_id ) ) {
				throw new RequestException( 'invalid_provider', 'The selected monetization provider does not exist.', [ 'field_id' => 'provider_id', 'status' => 400 ] );
			}

			$app = HostedApplicationService::get_app_by_id( $app_type, $app_id );

			if ( ! $app ) {
				throw new RequestException( 'app_not_found' );
			}

			$this->check_app_ownership( $app );

			$monetization = Monetization::get_by_app( $app->get_type(), $app->get_id() ) ?: new Monetization();

			if ( ! $monetization->exists() ) {
				$this->check_permissions( 'monetization.create' );

				$monetization
					->set_app_id( $app->get_id() )
					->set_app_type( $app->get_type() );

			} else {
				$this->check_permissions( 'monetization.update' );
			}

			if ( $tier_id ) {
				// Only a tier of this app's monetization can be edited here.
				$pricing_tier = $monetization->get_tier( $tier_id )
					?? throw new RequestException( 'resource_not_found', 'This app has no such pricing tier.', [ 'status' => 404 ] );

				$this->check_permissions( 'monetization.pricing.update' );
			} else {
				$pricing_tier = new PricingTier();
				$this->check_permissions( 'monetization.pricing.create' );
			}

			$full_provider_id = '';
			$provider_data    = [];

			if ( $provider ) {
				// Raw input: the provider validates and normalizes its own fields.
				$submitted     = (array) $request->get( 'provider_data', [], false );
				$provider_data = $provider->prepare_tier_data( (array) ( $submitted[ $provider_id ] ?? [] ), $app );

				if ( $provider_data instanceof \SmartLicenseServer\Exceptions\Exception ) {
					$data = $provider_data->get_error_data();

					throw new RequestException( $provider_data->get_error_code(), $provider_data->get_error_message(), [
						'status'   => (int) ( $data['status'] ?? 400 ),
						'field_id' => isset( $data['field_id'] ) ? sprintf( 'provider_%s_%s', $provider_id, $data['field_id'] ) : 'provider_id',
					] );
				}

				$full_provider_id = MonetizationRegistry::make_provider_id( $provider_id, $provider->get_channel( $provider_data ) );
			}

			try {
				$pricing_tier
					->set_name( $tier_name )
					->set_term( (string) $term_unit, (int) $request->get( 'term_length', 1 ) )
					->set_max_sites( '' === $max_sites ? PricingTier::UNLIMITED_SITES : (int) $max_sites )
					->set_features( $features )
					->set_provider( $full_provider_id, $provider_data );
			} catch ( \InvalidArgumentException $e ) {
				throw new RequestException( 'invalid_input', $e->getMessage(), [ 'status' => 400 ] );
			}

			$monetization->add_tier( $pricing_tier );

			try {
				$saved = $monetization->save();
			} catch ( \Throwable ) {
				$saved = false;
			}

			if ( $saved ) {
				$response_data = [ 'success' => true, 'data' => [ 'message' => 'Saved' ] ];
				return ( new Response( 200, [], smliser_safe_json_encode( $response_data ) ) )
					->set_header( 'Content-Type', 'application/json; charset=utf-8' );
			}

			throw new RequestException( 'save_failed', 'Something went wrong during data persistence.', [ 'status' => 500 ] );

		} catch ( RequestException $e ) {
			return ( new Response() )
				->set_exception( $e )
				->set_header( 'Content-Type', 'application/json; charset=utf-8' );
		}
	}

	/**
	 * Handle delete monetization tier request.
	 * 
	 * @param Request $request
	 * @return Response
	 */
	public function delete_monetization_tier( Request $request ) : Response {
		try {
			$this->check_permissions( 'monetization.pricing.delete' );
			
			$monetization_id = $request->get( 'monetization_id', 0 );
			$tier_id         = $request->get( 'tier_id', 0 );

			if ( ! $monetization_id ) {
				throw new RequestException( 'invalid_input', __( 'Monetization ID is required.', 'smliser' ), ['status' => 400] );
			}

			if ( ! $tier_id ) {
				throw new RequestException( 'invalid_input', __( 'Tier ID is required.', 'smliser' ), ['status' => 400] );
			}

			$monetization = Monetization::get_by_id( $monetization_id );

			if ( ! $monetization ) {
				throw new RequestException( 'resource_not_found', __( 'Monetization not found.', 'smliser' ), ['status' => 404] );
			}

			$app = $monetization->get_app();
			if ( $app ) $this->check_app_ownership( $app );
			
			$tier = $monetization->get_tier( $tier_id )
				?? throw new RequestException( 'resource_not_found', 'This app has no such pricing tier.', [ 'status' => 404 ] );

			// A tier that licenses were issued from is archived, not deleted.
			if ( $tier->has_licenses() ) {
				$tier->set_status( PricingTier::STATUS_ARCHIVED )->save();

				$response_data = [ 'success' => true, 'data' => [ 'message' => 'Licenses were issued from this pricing tier, so it was archived instead: it issues no new licenses.', 'archived' => true ] ];
				return ( new Response( 200, [], smliser_safe_json_encode( $response_data ) ) )
					->set_header( 'Content-Type', 'application/json; charset=utf-8' );
			}

			$deleted = $monetization->delete_tier( $tier_id );

			if ( ! $deleted ) {
				throw new RequestException( 'internal_server_error', __( 'Failed to delete the pricing tier, please try again.', 'smliser' ), ['status' => 500] );
			}
			$response_data = [ 'success' => true, 'data' => [ 'message' => 'Pricing tier deleted successfully.'] ];
			return ( new Response( 200, [], smliser_safe_json_encode( $response_data ) ) )
				->set_header( 'Content-Type', 'application/json; charset=utf-8' );

		} catch ( RequestException $e ) {
			return ( new Response() )
				->set_exception( $e )
				->set_header( 'Content-Type', 'application/json; charset=utf-8' );
		}
	}

	/**
	 * Handle monetization status toggling
	 * 
	 * @param Request $request
	 */
	public function toggle_monetization( Request $request ) : Response {

		try {
			
			$this->check_permissions( 'monetization.change_status' );

			$monetization_id = (int) $request->get( 'monetization_id' );
			$enabled         = (bool) $request->getTyped( 'enabled', 'boolean', false );

			if ( ! $monetization_id ) {
				throw new RequestException( 'invalid_input', __( 'This monetization does not exist yet, please add a pricing tier first.', 'smliser' ), ['status' => 400] );
			}

			$monetization = Monetization::get_by_id( $monetization_id );

			if ( ! $monetization ) {
				throw new RequestException( 'resource_not_found', __( 'Monetization not found.', 'smliser' ), ['status' => 404] );
			}

			$app = $monetization->get_app();

			if ( $app ) $this->check_app_ownership( $app );

			$monetization->set_enabled( $enabled );
			$monetization->save();

			$message       = $enabled ? __( 'Monetization enabled successfully.', 'smliser' ) : __( 'Monetization disabled successfully.', 'smliser' );
			$response_data = [ 'success' => true, 'data' => [ 'message' => $message ] ];
			return  Response::json( $response_data )
				->set_header( 'Content-Type', 'application/json; charset=utf-8' );

		} catch ( RequestException $e ) {
			return Response::error( $e )
				->set_header( 'Content-Type', 'application/json; charset=utf-8' );
		}

	}

	/**
	 * Process license save request.
	 *
	 * An existing license is loaded and the submitted fields are applied to
	 * it; fields the form does not carry (its source, tier and user) are kept.
	 *
	 * Request fields: license_id (to update), licensee_fullname,
	 * licensee_email (required), service_id (generated for a new license when
	 * empty; kept when empty on update), app_type and app_slug (both empty for
	 * no app), status, max_allowed_domains (empty or negative for unlimited),
	 * start_date, end_date, features (comma or line separated).
	 * 
	 * @param Request $request The Request object.
	 * @return Response 
	 */
	public function save_license( Request $request ) : Response {
		try {
			$id                  = (int) $request->get( 'license_id', 0 );
			$app_type            = (string) $request->get( 'app_type', '' );
			$app_slug            = (string) $request->get( 'app_slug', '' );
			$service_id          = trim( (string) $request->get( 'service_id', '' ) );
			$max_allowed_domains = $request->get( 'max_allowed_domains', -1 );

			if ( '' === $max_allowed_domains || (int) $max_allowed_domains < 0 ) {
				$max_allowed_domains = -1;
			}

			$license        = $id ? License::get_by_id( $id ) : new License();
			$license_exists = $license?->exists() ?? false;

			if ( ! $license ) {
				throw new RequestException( 'resource_not_found', 'This license does not exist.', [ 'status' => 404 ] );
			}

			if ( $license_exists ) {
				$this->check_permissions( 'monetization.license.update' );
			} else {
				$this->check_permissions( 'monetization.license.create' );
			}

			try {
				$license->set_licensee_email( (string) $request->get( 'licensee_email', '' ) );
			} catch ( \InvalidArgumentException $e ) {
				throw new RequestException( 'invalid_email', $e->getMessage(), [ 'field_id' => 'licensee_email', 'status' => 400 ] );
			}

			if ( '' === $license->get_licensee_email() ) {
				throw new RequestException( 'missing_email', 'The licensee email is required.', [ 'field_id' => 'licensee_email', 'status' => 400 ] );
			}

			if ( '' !== $app_type && '' !== $app_slug ) {
				$app = HostedApplicationService::get_app_by_slug( $app_type, $app_slug )
					?? throw new RequestException( 'app_not_found', sprintf( 'The %s "%s" does not exist.', $app_type, $app_slug ), [ 'status' => 404 ] );

				$this->check_app_ownership( $app );
				$this->check_permissions( 'monetization.license.issue' );
				$license->set_app( $app );
			} else {
				$license->set_app( null )->set_app_prop( '', '' );
			}

			if ( '' !== $service_id ) {
				$license->set_service_id( $service_id );
			}

			$license->set_licensee_fullname( $request->get( 'licensee_fullname', '' ) )
				->set_status( (string) $request->get( 'status', '' ) )
				->set_max_allowed_domains( $max_allowed_domains )
				->set_start_date( $request->get( 'start_date', '' ) )
				->set_end_date( $request->get( 'end_date', '' ) )
				->set_features( preg_split( '/[,\r\n]+/', (string) $request->get( 'features', '' ) ) ?: [] );

			if ( ! $license->save() ) {
				throw new RequestException( 'license_error', 'Unable to save the license' );
			}

			$request->set( 'license', $license );

			$url = $this->urlmanager->admin_license_page_url( 'edit', [
				'id'      => $license->get_id(),
				'message' => 'Saved',
				
			] );

			$response_data = [
				'success'      => true,
				'message'      => sprintf( 'License %s successfully.', $license_exists ? 'Updated' : 'Created' ),
				'license'      => $license->to_array(),
				'redirect_url' => $url->url()
			];
			
			$code     = $license_exists ? 200 : 201;
			$response = Response::json( $response_data, $code );

			return $response;
		} catch ( RequestException $e ) {
			return Response::error( $e )
				->set_header( 'Content-Type', 'application/json; charset=utf-8' );
		}
	}

	/**
	 * License bulk action.
	 * 
	 * @param Request $request The request object.
	 * @return Response
	 */
	public function license_bulk_action( Request $request ) : Response {
		try {
			// Only system admin can run bulk action.
			$this->is_system_admin();

			$license_ids = $request->get( 'ids', [] );
			$action      = $request->get( 'bulk_action' );
			$affected    = 0;

			foreach( (array) $license_ids as $id ) {
				$license = License::get_by_id( $id );

				if ( ! $license ) {
					continue;
				}

				if ( 'delete' === strtolower( $action ) ) {
					$license->delete() && $affected++;
					continue;
				}

				$license->set_status( $action );
				$license->save() && $affected++;
			}

			$url = $this->urlmanager->admin_license_page_url()
				->add_query_param( 'message', \sprintf( '%s affected!', $affected ) );
			
			$response = Response::redirect( $url, 303 );

			return $response;
		} catch ( RequestException $e ) {
			return Response::error( $e );
		}

	}

	/**
	 * Save Monetization Provider options.
	 * 
	 * @param Request $request
	 */
	public function save_provider_options( Request $request ) : Response {

		try {

			$this->is_system_admin();
			
			$provider_id = $request->get( 'provider_id', null );

			if ( ! $provider_id || ! $this->registry->has( $provider_id ) ) {
				throw new RequestException( 'access_restricted', sprintf( 'The provider "%s" is not supported.', $provider_id ?? 'Unknown' ), [ 'status' => 403] );
			}

			$provider        = $this->registry->get_provider( $provider_id );
			$allowed_options = array_keys( $provider->get_settings_schema() );

			foreach( $allowed_options as $name ) {
				if ( $value = $request->post( $name, null ) ) {
					MonetizationRegistry::update_option( $provider->get_id(), $name, $value );
				} else {
					MonetizationRegistry::update_option( $provider->get_id(), $name, '' );
				}
			}

			$response_data = [ 'success' => true, 'data' => [ 'message' => 'Saved' ] ];
			return Response::json( $response_data );
			
		} catch ( RequestException $e ) {
			return Response::error( $e )
				->set_header( 'Content-Type', 'application/json; charset=utf-8' );
		}

	}

	/**
	 * Remove/Uninstall a domain from a license
	 * 
	 * @param Request $request The request object.
	 * @return Response
	 */
	public function uninstall_domain_from_license( Request $request ) : Response {
		try {
			$this->check_permissions( 'monetization.license.uninstall_domain' );

			$license_id = $request->get( 'license_id' );
			$domain     = $request->get( 'domain' );

			if ( ! $license_id ) {
				throw new RequestException( 'invalid_input', __( 'License ID is required.', 'smliser' ), ['status' => 400] );
			}

			if ( ! $domain ) {
				throw new RequestException( 'invalid_input', __( 'Provide the domain to uninstall.', 'smliser' ), ['status' => 400] );
			}

			$license = License::get_by_id( $license_id );

			if ( ! $license ) {
				throw new RequestException( 'resource_not_found', __( 'This license does not exist.', 'smliser' ), ['status' => 404] );
			}

			$app = $license->get_app();

			if ( $app ) $this->check_app_ownership( $app );

			if ( $license->is_new_domain( $domain ) ) {
				throw new RequestException( 'is_new_domain', __( 'The domain provided does not exist in this license.', 'smliser' ), ['status' => 404] );
			}

			$removed = $license->remove_activated_domain( $domain );
			$message = $removed ? \sprintf( 'The domain "%s" has been uninstalled', $domain ) : \sprintf( 'Unable to uninstall "%s"', $domain );
			

			$response_data = [ 'success' => true, 'data' => [ 'message' => $message ] ];
			return Response::json( $response_data );
		}  catch ( RequestException $e ) {
			return Response::error( $e )
				->set_header( 'Content-Type', 'application/json; charset=utf-8' );
		}
	}

	/**
	 * Generate download token for a license.
	 * 
	 * @param Request $request
	 * @return Response
	 */
	public function generate_app_download_token( Request $request ) : Response {
		try {
			$this->is_system_admin();
			
			$license_id = $request->get( 'license_id' );

			if ( ! $license_id ) {
				throw new RequestException( 'required_param', 'License ID is required.' );
			}

			$license = License::get_by_id( $license_id );

			if ( ! $license ) {
				throw new RequestException( 'resource_not_found', 'This license does not exist.' );
			}

			$default_expiry = (int) DateDuration::fromDays( 10 )->toSeconds();

			$expiry = $request->get( 'expiry', $default_expiry ) ?: $default_expiry;

			if ( is_string( $expiry ) ) {
				$expiry = ( (int) strtotime( $expiry ) ) - time();

				if ( $expiry < 0 ) {
					$expiry = $default_expiry;
				}
			}

			$token = DownloadToken::create_token( $license, $expiry );

			$response_data = [
				'success' => true,
				'data'    => [
					'token'                 => $token,
					'licensee_fullname'     => $license->get_licensee_fullname(),
					'document_download_url' => $this->urlmanager->document_download_url( $license->get_id(), [
						'download_token' => $token
					] ),
					'expiry' => gmdate( smliser_datetime_format(), time() + $expiry ),
				]
			];
			return Response::json( $response_data );
		} catch( Exception $e ) {
			return Response::error( $e )
				->set_header( 'Content-Type', 'application/json; charset=utf-8' );

		}
	}

	/**
	 * Delete a license.
	 * 
	 * @param Request $request
	 * @return Response
	 */
	public function delete_license( Request $request ) : Response {
		try {
			$license_id = $request->get( 'license_id' );
			$license    = License::get_by_id( $license_id );

			if ( ! $license ) {
				throw new RequestException( 'resource_not_found', 'License was not found', ['status' => 404] );
			}

			$success = true;

			if ( ! $license->delete() ) {
				$success = false;
			}

			$message  = $success ? 'License was deleted' : 'Unable to delete license';
			$location = $this->urlmanager->admin_license_page_url()
				->add_query_params( [
					'success' => $success,
					'message' => $message
				] );

			return Response::json( [
				'success' => true,
				'data'    => [
					'redirect' => true,
					'location' => $location->url(),
					'message'  => $message
				]
			] );

		} catch ( RequestException $e ) {
			$message  = $e->get_error_message();
			$location = $this->urlmanager->admin_license_page_url()
				->add_query_params( [
					'success' => false,
					'message' => $message
				] );

			return Response::json( [
				'success' => false,
				'data'    => [
					'redirect' => true,
					'location' => $location->url(),
					'message'  => $message
				]
			] );
		}
	}
